#!/usr/bin/env python3
"""Zip every plugin and write catalog.json + CATALOG.md.

usage: build_catalog.py <out-dir> <download-base-url>
Zips are reproducible (sorted entries, fixed timestamps), so a plugin's
sha256 only changes when its files change.
"""
import hashlib
import json
import pathlib
import sys
import tomllib
import zipfile

out = pathlib.Path(sys.argv[1])
base = sys.argv[2].rstrip("/")
out.mkdir(parents=True, exist_ok=True)
entries = []
for toml in sorted(pathlib.Path("plugins").glob("*/plugin.toml")):
    d = toml.parent
    m = tomllib.load(open(toml, "rb"))
    pid = m["id"]
    z = out / f"{pid}.zip"
    with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in sorted(p for p in d.rglob("*") if p.is_file()):
            info = zipfile.ZipInfo(f"{pid}/{f.relative_to(d).as_posix()}", date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, f.read_bytes())
    sha = hashlib.sha256(z.read_bytes()).hexdigest()
    preview = (d / "preview.png").is_file()
    entries.append({
        "id": pid,
        "name": m.get("name", pid),
        "version": m.get("version", ""),
        "author": m.get("author", ""),
        "description": m.get("description", ""),
        "permissions": m.get("permissions", []),
        "flashing": m.get("flashing", True),
        "download_url": f"{base}/{pid}.zip",
        "sha256": sha,
        "size": z.stat().st_size,
        "readme": f"plugins/{d.name}/README.md",
        "preview": f"plugins/{d.name}/preview.png" if preview else None,
    })
catalog = {"schema": 1, "plugins": entries}
pathlib.Path("catalog.json").write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + "\n")
rows = ["# Plugin catalog", "",
        "Generated by CI from `plugins/` on every push to main. Machine-readable: [catalog.json](catalog.json).", "",
        "| Plugin | Version | Author | Permissions | Flashing | Download |",
        "| --- | --- | --- | --- | --- | --- |"]
for e in entries:
    perms = ", ".join(f"`{p}`" for p in e["permissions"]) or "none"
    rows.append(f"| **[{e['name']}](plugins/{e['id']}/README.md)**<br><sub>{e['description']}</sub> | {e['version']} | {e['author']} | {perms} | "
                f"{'⚡ yes' if e['flashing'] else 'no'} | [{e['id']}.zip]({e['download_url']}) |")
pathlib.Path("CATALOG.md").write_text("\n".join(rows) + "\n")
print(f"{len(entries)} plugins")
